function generateCatalogOpportunities(): Opportunity[] {
  const list: Opportunity[] = [...CORE_OPPORTUNITIES];
  const modes: Opportunity['mode'][] = ['Remote', 'Hybrid', 'On-site'];
  // Spread deadlines evenly: <3 days (red), 4-14 days (orange), 15-30 days (green)
  const deadlineOffsets = [1, 2, 4, 6, 8, 10, 12, 14, 16, 18, 21, 24, 27, 30];

  let idx = 15;
  for (let c = 0; c < REAL_COMPANIES.length; c++) {
    const comp = REAL_COMPANIES[c];
    for (let r = 0; r < 5; r++) {
      const role = ROLE_TEMPLATES[(c * 3 + r * 2) % ROLE_TEMPLATES.length];
      const mode = modes[(c + r) % modes.length];
      const dlOffset = deadlineOffsets[(c + r * 3) % deadlineOffsets.length];
      const startOffset = ((c + r) % 4 === 0 ? 18 : 30) + ((c + r) % 25);
      const endOffset = startOffset + (role.type === 'Hackathon' ? 2 : 60 + ((r % 3) * 30));
      const stipend = Math.max(
        10000,
        role.stipendBase + ((c % 5) - 2) * 3000 + (comp.verified ? 2000 : 0)
      );

      list.push({
        id: `op-${idx++}`,
        title: role.type === 'Hackathon' ? `${comp.company} ${role.title}` : role.title,
        company: comp.company,
        type: role.type,
        domain: role.domain,
        mode,
        location: mode === 'Remote' ? 'Remote' : comp.city,
        stipend,
        stipendLabel: role.type === 'Hackathon' ? `₹${Math.round(stipend / 1000)}K prize` : undefined,
        durationLabel: role.duration,
        deadline: offsetDate(dlOffset),
        startDate: offsetDate(startOffset),
        endDate: offsetDate(endOffset),
        skills: role.skills,
        minSemester: role.minSem,
        description: `${role.desc} Hosted by ${comp.company}.`,
        sourcePlatform: comp.platform,
        officialUrl: comp.url,
        ownerOrg: comp.company,
        verified: comp.verified,
      });
    }
  }

  return list;
}

